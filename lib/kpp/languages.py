"""Notepad++-style A–Z Language menu: one small script action per language.

Kate's own list (Tools → Highlighting, action `tools_highlighting`) is grouped by category
and its per-language entries aren't real actions, so they can't be placed in another menu.
Kate++ therefore writes a Kate script with one action per language (each runs Kate's
`set-highlight <name>` command on the current tab); menus.py arranges those actions in A, B,
C, … submenus. The language names come from Kate's syntax library (`ksyntaxhighlighter6
--list`), so languages added by a Kate update appear on the next apply / background run.
"""
from __future__ import annotations

import json
import re
import subprocess

from . import core

SCRIPT = "katepart5/script/commands/kate-plusplus-languages.js"
ACTION_PREFIX = "tools_scripts_"   # Kate's action name for a script action: prefix + function
CATEGORY = "Language"              # its submenu under Tools → Scripts

# Building blocks other definitions include; Kate's own menu hides them (hidden="true" in
# KDE's syntax-highlighting sources). Names with a "/" are template hybrids (Jinja/C++,
# CSS/PHP, …), mostly hidden too; they stay reachable under "All Languages".
HIDDEN = {"Alerts", "Comments", "GCCExtensions", "Modelines", "SPDX-Comments", "None"}

LISTERS = ("ksyntaxhighlighter6", "ksyntaxhighlighter5", "kate-syntax-highlighter")


def available() -> list:
    """Visible language names, A–Z (case-insensitive); [] when Kate's syntax tool is missing."""
    for tool in LISTERS:
        if not core.have(tool):
            continue
        try:
            out = subprocess.run([tool, "--list"], capture_output=True, text=True, timeout=20).stdout
        except (OSError, subprocess.SubprocessError):
            continue
        names = {n.strip() for n in out.splitlines()} - HIDDEN - {""}
        names = [n for n in names if "/" not in n]
        if names:
            return sorted(names, key=lambda n: (n.casefold(), n))
    return []


def function_name(language: str) -> str:
    """A JavaScript identifier per language, stable and unique (C++ → kppLang_C_2b_2b)."""
    return "kppLang_" + re.sub(r"[^A-Za-z0-9]", lambda m: "_%02x" % ord(m.group(0)), language)


def action_name(language: str) -> str:
    return ACTION_PREFIX + function_name(language)


def script(languages) -> str:
    funcs = [function_name(n) for n in languages]
    header = {"author": "kate-plusplus contributors", "license": "MIT", "revision": 1,
              "kate-version": "5.1", "functions": funcs,
              "actions": [{"function": f, "name": n.replace("&", "&&"), "category": CATEGORY}
                          for f, n in zip(funcs, languages)]}
    lines = ["// Generated by Kate++ (kate-plusplus apply): the A–Z Language menu. Don't edit.",
             "var katescript = " + json.dumps(header, indent=1, ensure_ascii=False) + ";",
             "",
             "function action(cmd) {",
             "    return katescript.actions.filter(function (a) { return a[\"function\"] == cmd; })[0];",
             "}",
             "",
             "function kppSetLanguage(name) { view.executeCommand(\"set-highlight\", name); }",
             ""]
    lines += [f"function {f}() {{ kppSetLanguage({json.dumps(n, ensure_ascii=False)}); }}"
              for f, n in zip(funcs, languages)]
    return "\n".join(lines) + "\n"


def write_script(kate, languages) -> bool:
    """(Re)write the generated script; False when it was already up to date."""
    path = kate.data / SCRIPT
    text = script(languages)
    try:
        if path.read_text(encoding="utf-8") == text:
            return False
    except OSError:
        pass
    core.atomic_write(path, text, 0o644)
    return True


def remove_script(kate):
    (kate.data / SCRIPT).unlink(missing_ok=True)


def groups(languages):
    """[(letter, [language, ...]), ...]: A–Z, plus "#" first for names starting otherwise."""
    out = {}
    for n in languages:
        k = n[0].upper() if n[0].isascii() and n[0].isalpha() else "#"
        out.setdefault(k, []).append(n)
    return sorted(out.items(), key=lambda kv: (kv[0] != "#", kv[0]))
